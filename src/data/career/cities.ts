/** "São José dos Campos" → "sao-jose-dos-campos". */
const slug = (name: string): string =>
  name
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');

/** ID `${uf}-${nome}` (ex.: "sp-campinas"): único, porque nenhum estado tem dois municípios com o mesmo nome. */
export const CAREER_CITIES: CareerCity[] = Object.entries(ROWS).flatMap(([stateId, rows]) =>
  rows.map(([name, voters, councilSeats]) => ({ id: `${stateId}-${slug(name)}`, stateId, name, voters, councilSeats })),
);
